"""Measure the catalog on a folder of prose: how often each rule fires, and thresholds that fit.

A rule's level never follows these numbers. They tell a project what a rule
will flag in writing it considers good, and they set the density thresholds.
"""
import json
import tomllib
from pathlib import Path

from slopstop import check, rules, text

MIN_WORDS = 150


def measure(raws: list[str], name: str, share: float = 0.05) -> dict:
    docs, reps = [], []
    for raw in raws:
        if text.word_count(raw) < MIN_WORDS:
            continue
        reps.append(check.run(raw))
        docs.append(check.document(raw))
    n, words = len(reps), sum(r.words for r in reps)
    langs = sorted({r.lang for r in reps})
    out = {"set": name, "files": n, "words": words, "langs": langs, "share": share, "rules": {}, "thresholds": {}}
    for r in rules.load():
        if r.lang not in ("any", *langs):
            continue
        key = r.id if r.lang == "any" else f"{r.id}/{r.lang}"
        fired = [rep for rep in reps if rep.lang in (r.lang,) or r.lang == "any"]
        hits = [f for rep in fired for f in rep.findings if f.rule == r.id]
        files = sum(any(f.rule == r.id for f in rep.findings) for rep in fired)
        out["rules"][key] = {"level": r.level, "files": files, "share": round(files / max(n, 1), 3),
                             "per_1000_words": round(len(hits) * 1000 / max(words, 1), 3)}
        if r.tune and docs:
            best = _tune(r, docs, share)
            out["thresholds"][r.id] = {"current": r.threshold,
                                       "suggested": best[0] if best else None,
                                       "share_at_suggested": best[1] if best else None}
    return out


def _cut(r: rules.Rule, doc) -> int:
    """The threshold where this document flips between flagged and not, by binary search.

    For a rule that flags less as the threshold grows, the smallest threshold that
    does not flag it (hi + 1 if none does); for tune_up rules, the smallest that does.
    """
    lo, hi = r.tune
    a, b = lo, hi + 1
    while a < b:
        mid = (a + b) // 2
        fired = bool(r.scan(doc, r, mid))
        if fired != r.tune_up:      # still flagged (or, tune_up, not yet flagged)
            a = mid + 1
        else:
            b = mid
    return a


def _tune(r: rules.Rule, docs: list, share: float) -> tuple[int, float] | None:
    """The strictest threshold in range that flags at most `share` of the documents."""
    cuts = [_cut(r, d) for d in docs]
    lo, hi = r.tune
    order = range(hi, lo - 1, -1) if r.tune_up else range(lo, hi + 1)
    for t in order:
        flagged = sum((t >= c) if r.tune_up else (t < c) for c in cuts) / len(docs)
        if flagged <= share:
            return t, round(flagged, 3)
    return None


def files_in(folder: Path) -> list[str]:
    return [p.read_text(encoding="utf-8", errors="replace")
            for p in sorted(folder.rglob("*")) if p.is_file() and p.suffix in (".md", ".txt")
            and ".orig." not in p.name]


def render_text(res: dict) -> str:
    out = [f"{res['set']}: {res['files']} files, {res['words']} words, {'/'.join(res['langs'])}",
           f"{'rule':<24}{'level':<7}{'files':>7}{'share':>8}{'per 1k':>9}"]
    for k, v in res["rules"].items():
        out.append(f"{k:<24}{v['level']:<7}{v['files']:>7}{v['share']:>8.1%}{v['per_1000_words']:>9.2f}")
    if res["thresholds"]:
        out.append(f"\nthresholds that flag at most {res['share']:.0%} of these files:")
        for k, v in res["thresholds"].items():
            sug = "none in range" if v["suggested"] is None else f"{v['suggested']} ({v['share_at_suggested']:.1%})"
            out.append(f"  {k:<18} {v['current']} -> {sug}")
    return "\n".join(out) + "\n"


def _toml_value(v) -> str:
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    return str(v)


def write_config(path: Path, thresholds: dict[str, int]) -> None:
    """Merge thresholds into a slopstop.toml, keeping its other settings."""
    data = tomllib.loads(path.read_text()) if path.exists() else {}
    data.setdefault("thresholds", {}).update(thresholds)
    lines = [f"{k} = {_toml_value(v)}" for k, v in data.items() if not isinstance(v, dict)]
    for table, vals in data.items():
        if isinstance(vals, dict):
            lines += ["", f"[{table}]"] + [f"{k} = {_toml_value(v)}" for k, v in vals.items()]
    path.write_text("\n".join(lines).lstrip("\n") + "\n")


def rules_markdown(cals: list[dict]) -> str:
    """docs/rules.md: every rule, and the share of files it flags in each calibration set."""
    head = ["# Rules", "",
            "Generated by `make rules-doc` from the catalog and `docs/calibration/*.json`. "
            "Each set column is the share of that set's files where the rule fires at least once; "
            "`docs/calibration/README.md` says what each set is.", ""]
    cols = [c["set"] for c in cals]
    head.append("| rule | lang | level | fix | why | " + " | ".join(cols) + " |")
    head.append("|---" * (5 + len(cols)) + "|")
    for r in rules.load():
        key = r.id if r.lang == "any" else f"{r.id}/{r.lang}"
        cells = []
        for c in cals:
            v = c["rules"].get(key)
            cells.append("" if v is None else f"{v['share']:.0%}")
        head.append(f"| {r.id} | {r.lang} | {r.level} | {r.kind} | {r.why} | " + " | ".join(cells) + " |")
    head += ["", "Thresholds (current, and the value that flags at most each set's share of files):", ""]
    tuned = [r for r in rules.load() if r.tune]
    head.append("| rule | current | " + " | ".join(cols) + " |")
    head.append("|---" * (2 + len(cols)) + "|")
    for r in tuned:
        cells = []
        for c in cals:
            t = c["thresholds"].get(r.id)
            cells.append("" if not t or t["suggested"] is None else str(t["suggested"]))
        head.append(f"| {r.id} | {r.threshold} | " + " | ".join(cells) + " |")
    return "\n".join(head) + "\n"
